// Make light link-preview copies of the site's images: public/og/<name>.jpg, 1200×630, ~100–200 KB.
// WhatsApp (and some other apps) skip the preview thumbnail when the image is too heavy.
// The full-size photos used on the pages are not touched.
//
// Run after adding or changing a page image used for sharing:  node scripts/make-og-images.mjs
import fs from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

const root = process.cwd()
const srcDir = path.join(root, 'public', 'images')
const outDir = path.join(root, 'public', 'og')
fs.mkdirSync(outDir, { recursive: true })

// Every /images/... file the code mentions (any of them can be passed to pageMetadata as the share image)
const used = new Set()
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).forEach((e) => {
  const p = path.join(d, e.name)
  if (e.isDirectory()) return walk(p)
  if (!/\.(tsx?|mjs)$/.test(e.name)) return
  for (const m of fs.readFileSync(p, 'utf8').matchAll(/\/images\/([\w.-]+\.(?:jpe?g|png|webp))/g)) used.add(m[1])
})
walk(path.join(root, 'src'))

const made = []
for (const file of [...used].sort()) {
  const input = path.join(srcDir, file)
  if (!fs.existsSync(input)) continue
  const name = file.replace(/\.(jpe?g|png|webp)$/, '.jpg')
  const { width = 1, height = 1 } = await sharp(input).metadata()
  await sharp(input)
    // portrait photos: keep the top (faces); landscape: let sharp pick the busiest area
    .resize(1200, 630, { fit: 'cover', position: height > width ? 'north' : 'attention' })
    .flatten({ background: '#faf8f2' })
    .jpeg({ quality: 78, mozjpeg: true })
    .toFile(path.join(outDir, name))
  made.push([file, name, Math.round(fs.statSync(path.join(outDir, name)).size / 1024)])
}

// List the code reads to swap /images/x for /og/x in share tags
const manifest = `// Generated by scripts/make-og-images.mjs, do not edit by hand.
// Maps a page image to its light 1200×630 link-preview copy in /public/og.
export const OG_IMAGE_COPIES: Record<string, string> = {
${made.map(([f, n]) => `  '/images/${f}': '/og/${n}',`).join('\n')}
}
`
fs.writeFileSync(path.join(root, 'src', 'lib', 'ogImages.ts'), manifest)
for (const [f, n, kb] of made) console.log(`${String(kb).padStart(4)} KB  og/${n}  (from images/${f})`)
console.log(`${made.length} preview images written`)
